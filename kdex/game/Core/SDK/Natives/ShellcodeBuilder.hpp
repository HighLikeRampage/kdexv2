#pragma once
#include <cstdint>
#include <vector>
#include <cstring>

class ShellcodeBuilder {
public:
  struct CitizenShellcode {
    std::vector<uint8_t> buffer;
    size_t PATCH_QUEUE;
    size_t PATCH_ORIGFUNC;
  };

  static CitizenShellcode buildCitizenShellcode() {
    CitizenShellcode result;
    result.buffer = {
      0x9C,
      0x50, 0x51,
      0x48, 0xBA, 0,0,0,0,0,0,0,0,
      0x52,
      0x48, 0x83, 0x82, 0xC0,0x00,0x00,0x00, 0x01,
      0x0F, 0xB6, 0x02,
      0x85, 0xC0,
      0x0F, 0x84, 0x40, 0x00, 0x00, 0x00,
      0xC6, 0x02, 0x00,
      0x4C, 0x8D, 0x92, 0xA0,0x00,0x00,0x00,
      0x4C, 0x8D, 0x9A, 0xC8,0x00,0x00,0x00,
      0x4D, 0x89, 0x1A,
      0x8B, 0x4A, 0x18,
      0x41, 0x89, 0x4A, 0x08,
      0x48, 0x8D, 0x42, 0x20,
      0x49, 0x89, 0x42, 0x10,
      0x48, 0x8B, 0x42, 0x08,
      0x48, 0x8D, 0x8A, 0xA0,0x00,0x00,0x00,
      0x48, 0x83, 0xEC, 0x28,
      0xFF, 0xD0,
      0x48, 0x83, 0xC4, 0x28,
      0x48, 0x8B, 0x14, 0x24,
      0xC6, 0x42, 0x01, 0x01,
      0x5A, 0x59, 0x58, 0x9D,
      0xFF, 0x25, 0x00, 0x00, 0x00, 0x00,
      0,0,0,0,0,0,0,0,
    };
    result.PATCH_QUEUE = 5;
    result.PATCH_ORIGFUNC = 107;
    return result;
  }

  struct DirectCallShellcode {
    std::vector<uint8_t> buffer;
    size_t dataOff;
    size_t D_STACK_TOP;
    size_t D_SAVED_RAX;
    size_t D_SAVED_RSP;
    size_t D_SAVED_RIP;
    size_t D_HANDLER;
    size_t D_ARGCOUNT;
    size_t D_DONE;
    size_t D_RESULT;
    size_t D_ARG;
    size_t D_SIZE;
  };

  static DirectCallShellcode buildDirectCall() {
    DirectCallShellcode result;
    const size_t D_STACK_TOP=0x00, D_SAVED_RAX=0x08, D_SAVED_RSP=0x10, D_SAVED_RIP=0x18;
    const size_t D_HANDLER=0x20, D_ARGCOUNT=0x28, D_DONE=0x30;
    const size_t D_RESULT=0x40, D_ARG=0x60, D_SIZE=0xA0;

    std::vector<uint8_t> enc;
    auto emit = [&](const std::initializer_list<uint8_t>& bytes) {
      for (auto b : bytes) enc.push_back(b);
    };

    emit({0x48, 0x89, 0x05, 0, 0, 0, 0});
    enc[3] = (D_SAVED_RAX & 0xFF); enc[4] = ((D_SAVED_RAX >> 8) & 0xFF);
    emit({0x48, 0x89, 0x25, 0, 0, 0, 0});
    emit({0x48, 0x8B, 0x05, 0, 0, 0, 0});
    emit({0x48, 0x89, 0xC4});

    emit({0x55, 0x9C});
    emit({0x51, 0x52, 0x41, 0x50, 0x41, 0x51, 0x41, 0x52, 0x41, 0x53});
    emit({0x53, 0x56, 0x57});
    emit({0x41, 0x54, 0x41, 0x55, 0x41, 0x56, 0x41, 0x57});

    emit({0x48, 0x83, 0xEC, 0x60});
    emit({0x0F, 0x29, 0x04, 0x24});
    emit({0x0F, 0x29, 0x4C, 0x24, 0x10});
    emit({0x0F, 0x29, 0x54, 0x24, 0x20});
    emit({0x0F, 0x29, 0x5C, 0x24, 0x30});
    emit({0x0F, 0x29, 0x64, 0x24, 0x40});
    emit({0x0F, 0x29, 0x6C, 0x24, 0x50});

    emit({0x48, 0x81, 0xEC, 0xB0, 0x00, 0x00, 0x00});

    emit({0x31, 0xC0});
    emit({0x48, 0x89, 0x84, 0x24, 0x80, 0x00, 0x00, 0x00});
    emit({0x48, 0x89, 0x84, 0x24, 0x88, 0x00, 0x00, 0x00});
    emit({0x48, 0x89, 0x84, 0x24, 0x90, 0x00, 0x00, 0x00});
    emit({0x48, 0x89, 0x84, 0x24, 0x98, 0x00, 0x00, 0x00});

    emit({0x48, 0x8D, 0x84, 0x24, 0x80, 0x00, 0x00, 0x00});
    emit({0x48, 0x89, 0x44, 0x24, 0x20});

    emit({0x48, 0x8B, 0x05, 0, 0, 0, 0});
    emit({0x89, 0x44, 0x24, 0x28});

    emit({0x48, 0x8D, 0x44, 0x24, 0x40});
    emit({0x48, 0x89, 0x44, 0x24, 0x30});
    emit({0xC7, 0x44, 0x24, 0x38, 0x00, 0x00, 0x00, 0x00});

    const size_t argOffs[] = {0x40, 0x48, 0x50, 0x58, 0x60, 0x68, 0x70, 0x78};
    for (int i = 0; i < 8; i++) {
      emit({0x48, 0x8B, 0x05, 0, 0, 0, 0});
      emit({0x48, 0x89, 0x44, 0x24, static_cast<uint8_t>(argOffs[i])});
    }

    emit({0x48, 0x8D, 0x4C, 0x24, 0x20});
    emit({0x48, 0x8B, 0x05, 0, 0, 0, 0});
    emit({0xFF, 0xD0});

    emit({0x48, 0x8B, 0x84, 0x24, 0x80, 0x00, 0x00, 0x00});
    emit({0x48, 0x89, 0x05, 0, 0, 0, 0});
    emit({0x48, 0x8B, 0x84, 0x24, 0x88, 0x00, 0x00, 0x00});
    emit({0x48, 0x89, 0x05, 0, 0, 0, 0});
    emit({0x48, 0x8B, 0x84, 0x24, 0x90, 0x00, 0x00, 0x00});
    emit({0x48, 0x89, 0x05, 0, 0, 0, 0});

    emit({0x48, 0x81, 0xC4, 0xB0, 0x00, 0x00, 0x00});

    emit({0x0F, 0x28, 0x04, 0x24});
    emit({0x0F, 0x28, 0x4C, 0x24, 0x10});
    emit({0x0F, 0x28, 0x54, 0x24, 0x20});
    emit({0x0F, 0x28, 0x5C, 0x24, 0x30});
    emit({0x0F, 0x28, 0x64, 0x24, 0x40});
    emit({0x0F, 0x28, 0x6C, 0x24, 0x50});
    emit({0x48, 0x83, 0xC4, 0x60});

    emit({0x41, 0x5F, 0x41, 0x5E, 0x41, 0x5D, 0x41, 0x5C});
    emit({0x5F, 0x5E, 0x5B});
    emit({0x41, 0x5B, 0x41, 0x5A, 0x41, 0x59, 0x41, 0x58, 0x5A, 0x59});
    emit({0x9D, 0x5D});

    emit({0xF0, 0x48, 0xFF, 0x05, 0, 0, 0, 0});
    emit({0x48, 0x8B, 0x25, 0, 0, 0, 0});
    emit({0x48, 0x8B, 0x05, 0, 0, 0, 0});
    emit({0xFF, 0x25, 0, 0, 0, 0});

    result.dataOff = (enc.size() + 15) & ~15;
    result.buffer.resize(result.dataOff + D_SIZE);
    std::memcpy(result.buffer.data(), enc.data(), enc.size());

    result.D_STACK_TOP = D_STACK_TOP;
    result.D_SAVED_RAX = D_SAVED_RAX;
    result.D_SAVED_RSP = D_SAVED_RSP;
    result.D_SAVED_RIP = D_SAVED_RIP;
    result.D_HANDLER = D_HANDLER;
    result.D_ARGCOUNT = D_ARGCOUNT;
    result.D_DONE = D_DONE;
    result.D_RESULT = D_RESULT;
    result.D_ARG = D_ARG;
    result.D_SIZE = D_SIZE;

    return result;
  }
};
